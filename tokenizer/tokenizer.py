# MAIN
# ============================================================================


def main() -> None:

    args = parse_args()

    try:

        metadata = run_pipeline(
            force=args.force,
            vocab_size=args.vocab_size,
        )

        print_summary(metadata)

    except Exception as exc:

        print(
            "\n❌ Tokenizer pipeline failed:"
        )

        print(
            f"   {exc}\n"
        )

        raise


if __name__ == "__main__":
    main()