def parse_args() -> argparse.Namespace:

    parser = argparse.ArgumentParser(
        description=(
            "Train a joint SentencePiece Unigram tokenizer "
            "for Amharic → Afaan Oromo translation."
        )
    )

    parser.add_argument(
        "--vocab-size",
        type=int,
        default=VOCAB_SIZE,
        help="Vocabulary size (default: 10,000)",
    )

    parser.add_argument(
        "--force",
        action="store_true",
        help=(
            "Delete existing tokenizer outputs and "
            "retrain the tokenizer."
        ),
    )

    return parser.parse_args()


